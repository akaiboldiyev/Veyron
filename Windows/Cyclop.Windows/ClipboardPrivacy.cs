using System.Runtime.InteropServices;

namespace Cyclop.Windows;

internal static class ClipboardPrivacy
{
    [DllImport("user32.dll",CharSet=CharSet.Unicode,SetLastError=true)]private static extern uint RegisterClipboardFormat(string name);
    [DllImport("user32.dll")]private static extern bool IsClipboardFormatAvailable(uint format);
    [DllImport("user32.dll",SetLastError=true)]private static extern bool OpenClipboard(nint owner);
    [DllImport("user32.dll")]private static extern bool CloseClipboard();
    [DllImport("user32.dll")]private static extern nint GetClipboardData(uint format);
    [DllImport("kernel32.dll")]private static extern nint GlobalLock(nint memory);
    [DllImport("kernel32.dll")]private static extern bool GlobalUnlock(nint memory);

    public static bool IsSensitive()
    {
        foreach(var marker in new[]{"org.nspasteboard.ConcealedType","org.nspasteboard.TransientType","org.nspasteboard.AutoGeneratedType"})
        {
            var format=RegisterClipboardFormat(marker);
            if(format!=0&&IsClipboardFormatAvailable(format))return true;
        }
        var exclude=RegisterClipboardFormat("ExcludeClipboardContentFromMonitorProcessing");
        if(exclude!=0&&IsClipboardFormatAvailable(exclude))return true;
        var canInclude=RegisterClipboardFormat("CanIncludeInClipboardHistory");
        if(canInclude==0||!IsClipboardFormatAvailable(canInclude)||!OpenClipboard(0))return false;
        try
        {
            var handle=GetClipboardData(canInclude);if(handle==0)return false;
            var pointer=GlobalLock(handle);if(pointer==0)return false;
            try{return Marshal.ReadInt32(pointer)==0;}
            finally{GlobalUnlock(handle);}
        }
        finally{CloseClipboard();}
    }
}
